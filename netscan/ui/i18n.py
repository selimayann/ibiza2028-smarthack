def ro_needs_de(n: int) -> bool:
    """În română, după numerele care se termină în 00 sau 20-99 vine „de”: „20 de puncte”, „100 de puncte”,
    dar „19 puncte”, „101 puncte”. Pentru 0 și 1 nu se pune niciodată."""
    n = abs(int(n))
    return n >= 20 and (n % 100 == 0 or n % 100 >= 20)


def count_words(lang: str, n: int, one: str, many: str) -> str:
    """Un număr cu substantivul la forma corectă: count_words("ro", 1, "punct", "puncte") -> „1 punct”,
    („ro”, 5, …) -> „5 puncte”, („ro”, 40, …) -> „40 de puncte”; („en”, 40, "point", "points") -> „40 points”."""
    lang = normalize_lang(lang)
    if n == 1:
        return f"{n} {one}"
    if lang == "ro" and ro_needs_de(n):
        return f"{n} de {many}"
    return f"{n} {many}"


def count_phrase(lang: str, n: int, key_one: str, key_many: str) -> str:
    """Textul din TEXTS pentru un număr, sigur la plural. `key_one` și `key_many` sunt chei cu un singur „%s”
    pus chiar înaintea substantivului (ex. "risk_points_one" = „%s punct de risc”). Pentru 1 se folosește
    `key_one`; altfel `key_many`, iar în română se adaugă „de” când trebuie („40 de puncte de risc”).
    Dacă `key_many` începe cu o etichetă („Puncte de risc: %s”), numărul se pune așa cum e."""
    texts = TEXTS[normalize_lang(lang)]
    if n == 1:
        return texts.get(key_one, key_one) % n
    template = texts.get(key_many, key_many)
    num = str(n)
    if normalize_lang(lang) == "ro" and ro_needs_de(n) and template.startswith("%s "):
        num = f"{n} de"
    return template % num


