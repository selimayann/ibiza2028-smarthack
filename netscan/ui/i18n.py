_INFO_WORDS = {"ro": ("lucru de știut", "lucruri de știut"), "en": ("thing to know", "things to know")}


def verdict_counts_text(lang: str, high: int = 0, medium: int = 0, low: int = 0, info: int = 0) -> str:
    """„Probleme găsite: 1 cu risc ridicat și 2 cu risc mediu.” Doar categoriile care nu sunt zero (numerele vin
    din severitățile motorului). Doar „de știut”: „Nimic riscant, doar 2 lucruri de știut.” Nimic: ""."""
    lang = normalize_lang(lang)
    parts = [t(lang, f"verdict_part_{sev}") % n for sev, n in (("high", high), ("medium", medium), ("low", low)) if n]
    if not parts:
        return t(lang, "verdict_only_info") % count_words(lang, info, *_INFO_WORDS[lang]) if info else ""
    joined = parts[0] if len(parts) == 1 else ", ".join(parts[:-1]) + f" {t(lang, 'verdict_and')} " + parts[-1]
    return f"{t(lang, 'verdict_counts_lead')} {joined}."


# Aceleași porturi ca la protecția live; „de verificat” = acasă, de obicei n-ar trebui să fie deschise.
# Nu e o severitate din catalog (pe aceea o dă doar motorul): e doar un semn că merită să te uiți.
_PORT_ALIASES = {2323: 23, 8000: 80, 8080: 80, 8081: 80}
_PORT_CHECK = {21, 23, 80, 139, 445, 554, 1883, 3306, 3389, 5432, 5900, 6379, 27017}


def port_meaning(lang: str, port: int, label: str = "") -> dict:
    """Ce înseamnă pe înțeles un port deschis: {"text", "check"}. `label` (serviciul) e text nesigur, deja curățat."""
    lang = normalize_lang(lang)
    base = _PORT_ALIASES.get(port, port)
    key = f"port_{base}"
    if key in TEXTS[lang]:
        text = TEXTS[lang][key]
    elif label:
        text = TEXTS[lang]["port_other"] % label
    else:
        text = TEXTS[lang]["port_unknown"]
    return {"text": text, "check": base in _PORT_CHECK}
